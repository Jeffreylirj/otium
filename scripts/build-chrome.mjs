import { readFile, writeFile } from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const fields=await readFile(new URL('src/fields.mjs',root),'utf8');
const engine=await readFile(new URL('src/autofill.mjs',root),'utf8');
const adapter=await readFile(new URL('extension/dom-worker.js',root),'utf8');
const strip=source=>source.replace(/^import .*;\r?\n/gm,'').replace(/^export /gm,'');
await writeFile(new URL('extension/worker.bundle.js',root), `// Generated by npm run chrome:build.\n(()=>{\n${strip(fields)}\n${strip(engine)}\n${adapter}\n})();\n`);
